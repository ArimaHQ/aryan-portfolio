// Regenerates features/cinematic-home/html.generated.ts from index.html.
// Run after editing the cinematic home markup: node scripts/sync-cinematic-home.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = path.join(import.meta.dirname, '..', 'features', 'cinematic-home');
const html = readFileSync(path.join(dir, 'index.html'), 'utf8');
writeFileSync(
  path.join(dir, 'html.generated.ts'),
  `// Generated by scripts/sync-cinematic-home.mjs from index.html. Do not edit by hand.\nexport const CINEMATIC_HOME_HTML = ${JSON.stringify(html)};\n`,
);
